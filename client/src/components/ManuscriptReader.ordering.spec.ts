import { createPinia, setActivePinia } from "pinia";
import { flushPromises, mount } from "@vue/test-utils";
import { beforeEach, afterEach, describe, expect, it, vi } from "vitest";
import ManuscriptReader from "./ManuscriptReader.vue";
import { useAppStore } from "@/stores/app";
import { useCreativeLiveStore } from "@/features/creative-live/stores/creativeLive";
import { deliveryClient } from "@/features/delivery/services/deliveryClient";
beforeEach(() => { localStorage.clear(); setActivePinia(createPinia()); });
afterEach(() => vi.restoreAllMocks());
describe("reading without losing context", () => {
  it("refreshes revised prose without requiring the reader to change sections", async () => {
    const store = useAppStore();
    store.setCurrentProject("fiction", false);
    store.readerManifest = { units: [{ unit_id: "one", title: "第一节", content_hash: "draft-a" }] } as never;
    vi.spyOn(useCreativeLiveStore(), "connect").mockResolvedValue(undefined);
    vi.spyOn(deliveryClient, "readerState").mockResolvedValue({ position: { unit_id: "", scroll_ratio: 0 }, bookmarks: [] });
    const read = vi.spyOn(store, "loadReaderUnit").mockResolvedValue("第一次晋升的正文");
    const wrapper = mount(ManuscriptReader, { props: { mode: "reading" } });
    await flushPromises();
    expect(wrapper.get(".reader-scroll article").text()).toContain("第一次晋升的正文");
    read.mockResolvedValue("复核后晋升的新正文");
    store.readerManifest = { units: [{ unit_id: "one", title: "第一节", content_hash: "draft-b" }] } as never;
    await flushPromises();
    expect(wrapper.get(".reader-scroll article").text()).toContain("复核后晋升的新正文");
    wrapper.unmount();
  });
  it("does not let a late saved position undo a deliberate section change", async () => {
    const store = useAppStore();
    store.setCurrentProject("fiction", false);
    store.readerManifest = { units: [{ unit_id: "one", title: "第一节" }, { unit_id: "two", title: "第二节" }] } as never;
    vi.spyOn(useCreativeLiveStore(), "connect").mockResolvedValue(undefined);
    let restore!: (value: never) => void;
    vi.spyOn(deliveryClient, "readerState").mockImplementation(() => new Promise(resolve => { restore = resolve; }));
    vi.spyOn(store, "loadReaderUnit").mockImplementation(async id => `${id} 的正文`);
    const wrapper = mount(ManuscriptReader, { props: { mode: "reading" } });
    await flushPromises();
    await wrapper.get('button[title="下一节"]').trigger("click");
    await flushPromises();
    restore({ position: { unit_id: "one", scroll_ratio: .5 }, bookmarks: [] } as never);
    await flushPromises();
    expect(wrapper.get(".reader-title-block h2").text()).toBe("第二节");
    expect(wrapper.get(".reader-scroll article").text()).toContain("two 的正文");
    wrapper.unmount();
  });
  it("keeps the selected section when an older section finishes later", async () => {
    const store = useAppStore();
    store.setCurrentProject("fiction", false);
    store.readerManifest = { units: [{ unit_id: "one", title: "第一节" }, { unit_id: "two", title: "第二节" }] } as never;
    vi.spyOn(useCreativeLiveStore(), "connect").mockResolvedValue(undefined);
    vi.spyOn(deliveryClient, "readerState").mockResolvedValue({ position: { unit_id: "", scroll_ratio: 0 }, bookmarks: [] });
    let first!: (value: string) => void;
    const delayed = new Promise<string>(resolve => { first = resolve; });
    vi.spyOn(store, "loadReaderUnit").mockImplementation(id => id === "one" ? delayed : Promise.resolve("第二节的正文"));
    const wrapper = mount(ManuscriptReader, { props: { mode: "reading" } });
    await flushPromises();
    await wrapper.get('button[title="下一节"]').trigger("click");
    await flushPromises();
    expect(wrapper.get(".reader-scroll article").text()).toContain("第二节的正文");
    first("第一节的旧响应");
    await flushPromises();
    expect(wrapper.get(".reader-scroll article").text()).toContain("第二节的正文");
    await wrapper.get('button[title="搜索正文"]').trigger("click");
    await wrapper.get('input[aria-label="搜索正文内容"]').trigger("keydown", { key: "ArrowLeft" });
    expect(wrapper.get(".reader-title-block h2").text()).toBe("第二节");
    wrapper.unmount();
  });
});
